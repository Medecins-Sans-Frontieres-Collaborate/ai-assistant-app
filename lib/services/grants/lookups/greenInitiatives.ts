export interface GreenInitiativeMatch {
  /** Column-B subcategories, deduped, in sheet order. */
  subcategories: string[];
  /** Column-C climate-action classes, deduped, in sheet order. */
  actions: string[];
  /** The column-A phrases that matched (for logging/debugging). */
  matchedPhrases: string[];
  /** Matched column-A phrases per subcategory — the audit trail is shown in the
   *  Evidence Summary column so a reviewer can see why a key term was added. */
  phrasesBySubcategory: Record<string, string[]>;
}

function canon(s: string): string {
  return s
    .toLowerCase()
    .replace(/[\u2018\u2019\u201B\u00B4\u0060]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/\s+/g, ' ');
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Compiled lazily once: phrase -> word-bounded, whitespace-flexible regex.
let compiled: Array<{ re: RegExp; entry: GreenInitiativeEntry }> | null = null;
function compile() {
  if (compiled) return compiled;
  compiled = GREEN_INITIATIVE_TERMS.map((entry) => {
    const parts = canon(entry.phrase).split(' ').map(escapeRegExp);
    const re = new RegExp('\\b' + parts.join('\\s+') + '\\b', 'i');
    return { re, entry };
  });
  return compiled;
}

/**
 * Scan narrative text for supplied green-initiative phrases.
 * Returns empty arrays when nothing matches.
 */
export function matchGreenInitiatives(text: string): GreenInitiativeMatch {
  const subcategories: string[] = [];
  const actions: string[] = [];
  const matchedPhrases: string[] = [];
  const phrasesBySubcategory: Record<string, string[]> = {};
  if (!text)
    return { subcategories, actions, matchedPhrases, phrasesBySubcategory };
  const hay = canon(text);
  for (const { re, entry } of compile()) {
    if (!re.test(hay)) continue;
    matchedPhrases.push(entry.phrase);
    if (!subcategories.includes(entry.subcategory))
      subcategories.push(entry.subcategory);
    if (!actions.includes(entry.action)) actions.push(entry.action);
    const list = (phrasesBySubcategory[entry.subcategory] ??= []);
    if (!list.includes(entry.phrase)) list.push(entry.phrase);
  }
  return { subcategories, actions, matchedPhrases, phrasesBySubcategory };
}
