/** Bounded, durable garbage collection for expired claims and unreferenced resources. */
import { readSkill } from '@/lib/services/agentAccess/accessRulesStore';
import {
  AgentAccessConflictError,
  downloadBlob,
  uploadJson,
} from '@/lib/services/agentAccess/blobCas';

import type { BlobStorage } from '@/lib/utils/server/blob/blob';

import { deleteSkillChunks } from './skillSearch';
import { SkillDocument, SkillIdSchema } from './types';

import { createHash, randomUUID } from 'crypto';
import { z } from 'zod';

const JOB_PREFIX = 'system/agent-access/skill-cleanup/';
const CLAIM_PREFIX = 'system/agent-access/skill-continuations/';
/** Per-thread skill catalog memory (skillThreadState.ts); expires by `expiresAt`. */
const THREAD_PREFIX = 'system/agent-access/skill-threads/';
const EXPIRING_PREFIXES = [CLAIM_PREFIX, THREAD_PREFIX];
const CLAIM_CLOCK_SKEW_GRACE_MS = 60 * 60 * 1000;
const JobSchema = z.object({
  skillId: SkillIdSchema,
  fileId: z.string().regex(/^[a-f0-9-]{36}$/),
  notBefore: z.number(),
  chunkCount: z.number().int().min(0).max(300),
  endpoint: z.string().url().optional(),
  index: z.string().optional(),
  indexOnly: z.boolean().optional(),
});
let lastRun = 0;
let inFlight = false;
let timer: ReturnType<typeof setInterval> | undefined;
const cursors = new Map<string, string>();
const pages = new Map<string, string | undefined>();

/** Stage a delayed cleanup intent before originals are written, or retry a removal. */
export async function queueSkillCleanup(
  storage: BlobStorage,
  skillId: string,
  documents: SkillDocument[],
  notBefore = Date.now(),
  indexOnly = false,
): Promise<void> {
  for (const doc of documents) {
    const job = JobSchema.parse({
      skillId,
      fileId: doc.fileId,
      notBefore,
      chunkCount: doc.chunkCount ?? (doc.nextChunk > 0 ? 300 : 0),
      endpoint: doc.searchEndpoint,
      index: doc.searchIndex,
      indexOnly,
    });
    const key = createHash('sha256')
      .update(`${skillId}|${doc.fileId}|${randomUUID()}`)
      .digest('hex');
    try {
      await uploadJson(
        storage,
        `${JOB_PREFIX}${key}.json`,
        job,
        null,
        'skills.queueCleanup',
      );
    } catch (error) {
      if (!(error instanceof AgentAccessConflictError)) throw error;
    }
  }
  startSkillMaintenance(storage);
}

/** One bounded sweep; never deletes a resource still present in a live manifest. */
export async function sweepSkillMaintenance(
  storage: BlobStorage,
  now = Date.now(),
  limit = 10,
): Promise<void> {
  const signal = AbortSignal.timeout(5000);
  for (const prefix of [...EXPIRING_PREFIXES, JOB_PREFIX]) {
    let selected: string[];
    if (storage.listBlobsPage) {
      const page = await storage.listBlobsPage(
        prefix,
        pages.get(prefix),
        limit,
        signal,
      );
      pages.set(prefix, page.continuation);
      selected = page.names;
    } else {
      const names = (await storage.listBlobs(prefix)).sort();
      const cursor = cursors.get(prefix) ?? '';
      const after = names.filter((name) => name > cursor);
      selected = (after.length ? after : names).slice(0, limit);
    }
    signal.throwIfAborted();
    for (const name of selected) {
      signal.throwIfAborted();
      cursors.set(prefix, name);
      // Keys are generated by the server; malformed/alien entries are not targets.
      if (!/^[a-f0-9]{64}\.json$/.test(name.slice(prefix.length))) continue;
      try {
        const record = await downloadBlob(storage, name, 'skills.maintenance', {
          abortSignal: signal,
          maxBytes: prefix === THREAD_PREFIX ? 256 * 1024 : 4096,
        });
        if (!record) continue;
        const json = JSON.parse(record.buffer.toString('utf8'));
        if (EXPIRING_PREFIXES.includes(prefix)) {
          if (
            typeof json.expiresAt === 'number' &&
            Number.isFinite(json.expiresAt) &&
            json.expiresAt + CLAIM_CLOCK_SKEW_GRACE_MS <= now
          )
            await storage
              .getBlockBlobClient(name)
              .deleteIfExists({ abortSignal: signal });
          continue;
        }
        const job = JobSchema.parse(json);
        if (job.notBefore > now) continue;
        const current = await readSkill(storage, job.skillId, signal);
        const attached = current?.skill.documents.find(
          (doc) => doc.fileId === job.fileId,
        );
        if (
          attached &&
          (!job.indexOnly ||
            (attached.searchEndpoint === job.endpoint &&
              attached.searchIndex === job.index))
        ) {
          await storage
            .getBlockBlobClient(name)
            .deleteIfExists({ abortSignal: signal });
          continue;
        }
        if (!job.indexOnly)
          for (const part of ['original', 'prepared.json'])
            await storage
              .getBlockBlobClient(
                `system/agent-access/skill-resources/${job.skillId}/${job.fileId}/${part}`,
              )
              .deleteIfExists({ abortSignal: signal });
        if (job.chunkCount) {
          if (!job.endpoint || !job.index)
            throw new Error(
              'Historical index location is unknown; retain the cleanup job for operator reconciliation',
            );
          await deleteSkillChunks(
            job.fileId,
            job.chunkCount,
            { endpoint: job.endpoint, index: job.index },
            signal,
          );
        }
        await storage
          .getBlockBlobClient(name)
          .deleteIfExists({ abortSignal: signal });
      } catch (error) {
        console.warn(
          '[skills] Maintenance item retained for retry',
          name,
          error,
        );
      }
    }
  }
}

/**
 * Source refresh rides the maintenance cadence (docs/SKILLS_DESIGN.md §12):
 * due sources are synced one per sweep. Lazy import keeps the sync module
 * (network fetches) out of the chat path's module graph.
 */
async function refreshSkillSources(storage: BlobStorage): Promise<void> {
  try {
    const { autoSyncSkillSources } = await import('./skillSourceSync');
    await autoSyncSkillSources(storage);
  } catch (error) {
    console.warn('[skills] Source refresh skipped', error);
  }
}

/** Opportunistic sweeps are rate-limited per replica and independent of chat latency. */
export function startSkillMaintenance(storage: BlobStorage): void {
  // Automatic work requires bounded pagination. Legacy adapters can invoke
  // an explicit sweep, but must not repeatedly materialize entire prefixes.
  if (!storage.listBlobsPage) return;
  if (!timer) {
    timer = setInterval(() => startSkillMaintenance(storage), 60_000);
    timer.unref?.();
  }
  if (inFlight || Date.now() - lastRun < 60_000) return;
  inFlight = true;
  lastRun = Date.now();
  void sweepSkillMaintenance(storage)
    .catch((error) => console.warn('[skills] Maintenance unavailable', error))
    .then(() => refreshSkillSources(storage))
    .finally(() => {
      inFlight = false;
    });
}

/** Stops the unref'ed process timer, for shutdown hooks or isolated scheduler tests. */
export function stopSkillMaintenance(): void {
  if (timer) clearInterval(timer);
  timer = undefined;
  lastRun = 0;
}
